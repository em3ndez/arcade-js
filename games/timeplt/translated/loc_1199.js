// loc_1199  (ROM 0x1199–0x123A)
export function loc_1199(m) {
  const { regs, mem } = m;

  for (const [target, ret] of [
    [0x31b4, 0x119c], [0x1edf, 0x119f], [0x23e3, 0x11a2], [0x36af, 0x11a5],
    [0x0f97, 0x11a8], [0x47b3, 0x11ab], [0x43b7, 0x11ae], [0x28a1, 0x11b1],
    [0x0f97, 0x11b4], [0x2cbc, 0x11b7], [0x40d6, 0x11ba], [0x0f97, 0x11bd],
    [0x3b5f, 0x11c0], [0x3dda, 0x11c3], [0x3e36, 0x11c6], [0x0f97, 0x11c9],
    [0x3fea, 0x11cc], [0x4e4f, 0x11cf], [0x40b8, 0x11d2], [0x0f97, 0x11d5],
    [0x4dde, 0x11d8], [0x5205, 0x11db], [0x4d3a, 0x11de], [0x0809, 0x11e1],
    [0x1098, 0x11e4],
  ]) {
    m.push16(ret);
    m.step(target, 17); // call target
    m.call(target);
  }

  regs.a = mem.read8(0xa800);
  m.step(0x11e7, 13); // ld a,(0xa800)
  regs.a = regs.inc8(regs.a);
  m.step(0x11e8, 4); // inc a
  if (regs.fZ) {
    m.step(0x1271, 10); // jp z,0x1271 -- TAIL
    return m.call(0x1271);
  }
  m.step(0x11eb, 10); // jp z not taken
  regs.a = regs.dec8(regs.a);
  m.step(0x11ec, 4); // dec a
  if (regs.fNZ) {
    m.ret(11); // ret nz
    return;
  }
  m.step(0x11ed, 5); // ret nz not taken

  return m.call(0x11ed);
}
