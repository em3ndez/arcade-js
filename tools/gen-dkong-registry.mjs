// Codegen for Donkey Kong's browser-safe routine registry.
//
// The registry (routines.js) used to build its dispatch table by importing four
// hand-maintained re-export bundles (translated/boot.js, mainloop.js, nmi.js, state0.js)
// and scanning their exports at module load. Keeping those four files in sync with
// translated/ by hand is exactly the drift a codegen removes, and The Pit already
// GENERATES the equivalent static-import module. This is the same tool for DK: a
// static-import module the browser loads over normal relative HTTP, so no bundle needs
// hand-maintaining and the two games' registries work the same way.
//
// Run after adding or removing a translated routine:
//     node tools/gen-dkong-registry.mjs
// A sync-check test (games/dkong/test/registry-sync.test.js) fails if it goes stale.

import { readdirSync, writeFileSync } from "node:fs";
import { fileURLToPath, pathToFileURL } from "node:url";
import { dirname, join } from "node:path";

const HERE = dirname(fileURLToPath(import.meta.url));
const TRANSLATED = join(HERE, "..", "games", "dkong", "translated");
const OUT = join(TRANSLATED, "_registry.generated.js");

// A routine file: loc_ + exactly 4 hex digits + .js (excludes .test.js and helpers).
const ROUTINE_FILE = /^loc_[0-9a-f]{4}\.js$/;
// An export that owns a ROM address: loc_ + exactly 4 hex, both ends anchored, so a
// helper split loc_<parent>_<addr> (two groups) does NOT match.
const ADDR_NAME = /^loc_([0-9a-f]{4})$/;

/**
 * Discover, from translated/, every file's address-owning `loc_hhhh` exports — the
 * same rule the runtime registry used, done once at build time. Throws on a collision
 * (two names claiming one address) so a leaked helper is found, not silently shadowed.
 *
 * @returns {Promise<Array<{file:string, names:string[]}>>} files (import order) with
 *          their sorted loc_hhhh export names; files with no such export are omitted.
 */
export async function discover() {
  const files = readdirSync(TRANSLATED).filter((f) => ROUTINE_FILE.test(f)).sort();
  const perFile = [];
  const owner = new Map(); // addr -> claiming name, for a precise collision message
  for (const file of files) {
    const mod = await import(pathToFileURL(join(TRANSLATED, file)).href);
    const names = [];
    for (const [name, fn] of Object.entries(mod)) {
      if (typeof fn !== "function") continue;
      const m = ADDR_NAME.exec(name);
      if (!m) continue; // helper split / non-routine export — stays direct-called
      const addr = parseInt(m[1], 16);
      if (owner.has(addr)) {
        throw new Error(
          `registry: 0x${addr.toString(16).padStart(4, "0")} claimed by both ` +
            `${owner.get(addr)} and ${name} (in ${file}) — a helper leaked through the ` +
            "loc_hhhh filter; name it loc_<parent>_<addr> so it does not claim an address.",
        );
      }
      owner.set(addr, name);
      names.push(name);
    }
    if (names.length) perFile.push({ file, names: names.sort() });
  }
  if (!owner.has(0x0000)) throw new Error("registry: no reset routine at 0x0000 (loc_0000)");
  if (!owner.has(0x0066)) throw new Error("registry: no NMI routine at 0x0066 (loc_0066)");
  return perFile;
}

/** Render the generated module source from the discovered files. */
export function emit(perFile) {
  const out = [
    "// SPDX-License-Identifier: GPL-3.0-only",
    "// AUTO-GENERATED by tools/gen-dkong-registry.mjs — DO NOT EDIT BY HAND.",
    "// A browser-safe static routine registry: the address->function table baked as a",
    "// static import list so the web player can build it without node:fs / file:// imports.",
    "// Regenerate after adding/removing a translated routine:",
    "//     node tools/gen-dkong-registry.mjs",
    "",
  ];
  for (const { file, names } of perFile) {
    out.push(`import { ${names.join(", ")} } from "./${file}";`);
  }
  out.push("", "export const ORACLE_ROUTINES = new Map([");
  const entries = [];
  for (const { names } of perFile) {
    for (const n of names) entries.push(`  [0x${n.slice(4)}, ${n}],`); // loc_hhhh -> 0xhhhh
  }
  entries.sort(); // by the fixed-width 0xhhhh key — deterministic output
  out.push(...entries, "]);", "");
  return out.join("\n");
}

// Generate + write ONLY when invoked directly, so the sync-check test can import
// discover()/emit() without re-writing the file as a side effect.
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const perFile = await discover();
  writeFileSync(OUT, emit(perFile));
  const count = perFile.reduce((n, f) => n + f.names.length, 0);
  console.log(`generated ${OUT}\n  ${count} routines from ${perFile.length} files`);
}
